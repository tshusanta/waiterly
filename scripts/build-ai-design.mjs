// Writes the exact AI prompts and JSON schemas from server/prompt.ts into
// docs/AI_DESIGN.md, between the PROMPTS:START / PROMPTS:END markers, so the doc
// is word-for-word what the models receive. Run: npm run docs:prompts
import { readFileSync, writeFileSync } from 'node:fs'
import { createServer } from 'vite'

const server = await createServer({ server: { middlewareMode: true }, appType: 'custom', logLevel: 'error' })
try {
  const p = await server.ssrLoadModule('/server/prompt.ts')
  const fence = (lang, body) => '```' + lang + '\n' + body + '\n```'
  const exampleParseUser = p.buildParseUserMessage(
    'table 1 needs two more waters, 4 wants ranch',
    [1, 4, 7],
    [{ table: 4, text: 'Bring ranch on the side' }],
  )
  const examplePlanUser = p.buildPlanUserMessage([
    { id: 'a1', table: 4, text: 'Check satay sauce for peanuts', category: 'food', priority: 'high', flags: ['allergy'], waitMin: 2 },
  ])

  const section = [
    '<!-- PROMPTS:START (generated by scripts/build-ai-design.mjs from server/prompt.ts; do not edit by hand) -->',
    '',
    '### A. Parse: system prompt',
    'Used by `POST /api/parse`. Claude `claude-haiku-5-5` or Gemini `gemini-2.5-flash`.',
    '',
    fence('text', p.PARSE_SYSTEM_PROMPT),
    '',
    '### A2. Parse: user message format',
    'Per request. The section, open tasks and note are inserted here, so the system prompt stays identical on every call. Example:',
    '',
    fence('text', exampleParseUser),
    '',
    '### A3. Parse: output JSON schema',
    fence('json', JSON.stringify(p.PARSE_SCHEMA, null, 2)),
    '',
    '### B. Trip plan: system prompt',
    'Used by `POST /api/plan`. Claude `claude-haiku-5-5` or Gemini `gemini-2.5-flash`.',
    '',
    fence('text', p.PLAN_SYSTEM_PROMPT),
    '',
    '### B2. Trip plan: user message format (example)',
    fence('text', examplePlanUser),
    '',
    '### B3. Trip plan: output JSON schema',
    fence('json', JSON.stringify(p.PLAN_SCHEMA, null, 2)),
    '',
    '### C. Shift summary: system prompt',
    'Used by `POST /api/summary`. Claude `claude-sonnet-5-5` or Gemini `gemini-2.5-flash`. The user message is `Shift statistics:` followed by the stats JSON (numbers only, no task text).',
    '',
    fence('text', p.SUMMARY_SYSTEM_PROMPT),
    '',
    '### C2. Shift summary: output JSON schema',
    fence('json', JSON.stringify(p.SUMMARY_SCHEMA, null, 2)),
    '',
    '<!-- PROMPTS:END -->',
  ].join('\n')

  const path = 'docs/AI_DESIGN.md'
  const doc = readFileSync(path, 'utf8')
  const start = doc.indexOf('<!-- PROMPTS:START')
  const end = doc.indexOf('<!-- PROMPTS:END -->')
  if (start === -1 || end === -1) throw new Error('Markers not found in docs/AI_DESIGN.md')
  writeFileSync(path, doc.slice(0, start) + section + doc.slice(end + '<!-- PROMPTS:END -->'.length))
  console.log('Updated prompts section in docs/AI_DESIGN.md')
} finally {
  await server.close()
}
